// ============================================================================
// AlAqsa — Licensing / kill-switch.
//
// A license is a JSON payload signed with Ed25519. The PRIVATE key lives only
// in the separate license-issuer tool (Areen). The app embeds the PUBLIC key
// and verifies signatures — so no one but Areen can mint a valid license.
//
// A license carries an optional expiry (offline time-limit) and an optional
// heartbeat URL. On expiry/revoke the app LOCKS (shows renewal screen); it
// never deletes data. Perpetual licenses (issued on full payment) have no
// expiry and disable the heartbeat.
// ============================================================================

import crypto from 'node:crypto';
import fs from 'node:fs';
import { licensePath } from '../storage/paths';
import type { LicenseState } from '@shared/ipc';

/**
 * Embedded Ed25519 PUBLIC key (SPKI, base64). This placeholder is replaced with
 * the real public key generated by scripts/license-keygen at build time. The
 * matching private key is kept ONLY in the issuer tool and never shipped.
 */
/**
 * Injected by esbuild at BUILD time (see scripts/build-main.mjs).
 *
 * It must not be read from process.env at runtime: the customer's machine has
 * no such variable, so a packaged app would always fall back to the dev
 * placeholder and hand out perpetual licences. Baking the value into the
 * bundle is what makes a customer build actually enforce licensing.
 */
declare const __LICENSE_PUBLIC_KEY__: string;

export const LICENSE_PUBLIC_KEY_B64 =
  typeof __LICENSE_PUBLIC_KEY__ === 'string' && __LICENSE_PUBLIC_KEY__
    ? __LICENSE_PUBLIC_KEY__
    : 'REPLACE_WITH_ED25519_PUBLIC_KEY_SPKI_BASE64';

/**
 * True when no real public key was embedded at build time.
 *
 * In that state licence checks are bypassed so development is not blocked —
 * but a build like that must never reach a customer, because it grants a
 * perpetual licence to anyone. The UI surfaces this clearly (see the Licence
 * tab) and the packaging script refuses to produce an installer without a key
 * unless it is explicitly asked for a development build.
 */
export const IS_UNLICENSED_DEV_BUILD =
  LICENSE_PUBLIC_KEY_B64.startsWith('REPLACE_');

export interface LicensePayload {
  v: 1;
  clientName: string; // shop / owner name this license is bound to
  machineId?: string; // optional binding to a machine fingerprint
  issuedAt: string;
  expiresAt?: string; // omitted => perpetual
  perpetual: boolean;
  heartbeatUrl?: string; // optional remote kill-switch
  note?: string;
}

interface SignedLicense {
  payload: LicensePayload;
  sig: string; // base64 Ed25519 signature over canonical JSON of payload
}

function canonical(payload: LicensePayload): string {
  // Stable key order for signing/verification.
  return JSON.stringify(payload, Object.keys(payload).sort());
}

export function verifyLicenseString(licenseString: string): LicensePayload | null {
  try {
    const decoded = Buffer.from(licenseString.trim(), 'base64').toString('utf-8');
    const signed = JSON.parse(decoded) as SignedLicense;
    if (IS_UNLICENSED_DEV_BUILD) {
      // No key embedded: accept without verifying so development is unblocked.
      return signed.payload;
    }
    const pub = crypto.createPublicKey({
      key: Buffer.from(LICENSE_PUBLIC_KEY_B64, 'base64'),
      format: 'der',
      type: 'spki',
    });
    const ok = crypto.verify(
      null,
      Buffer.from(canonical(signed.payload)),
      pub,
      Buffer.from(signed.sig, 'base64'),
    );
    return ok ? signed.payload : null;
  } catch {
    return null;
  }
}

export class LicenseManager {
  private cached: LicensePayload | null = null;

  load(): void {
    try {
      if (fs.existsSync(licensePath())) {
        const str = fs.readFileSync(licensePath(), 'utf-8');
        this.cached = verifyLicenseString(str);
      }
    } catch {
      this.cached = null;
    }
  }

  activate(licenseString: string): LicenseState {
    const payload = verifyLicenseString(licenseString);
    if (!payload) return { status: 'revoked' };
    fs.writeFileSync(licensePath(), licenseString.trim(), 'utf-8');
    this.cached = payload;
    return this.state();
  }

  state(): LicenseState {
    // No license file at all.
    if (!this.cached) {
      // If no public key is configured yet (dev), treat as valid perpetual so
      // development is unblocked; production builds always embed a real key.
      if (IS_UNLICENSED_DEV_BUILD) {
        return { status: 'valid', perpetual: true, unlicensedDevBuild: true };
      }
      return { status: 'missing' };
    }
    if (this.cached.perpetual || !this.cached.expiresAt) {
      return { status: 'valid', perpetual: true };
    }
    const now = Date.now();
    const exp = new Date(this.cached.expiresAt).getTime();
    if (now > exp) return { status: 'expired', expiredAt: this.cached.expiresAt };
    return { status: 'valid', perpetual: false, expiresAt: this.cached.expiresAt };
  }

  /**
   * Optional heartbeat: contacts the issuer's endpoint. If the server responds
   * with { revoked: true } the app locks on next launch. Failure to reach the
   * server does NOT lock (avoids accidental lockout on connectivity loss).
   */
  async heartbeat(): Promise<'ok' | 'revoked' | 'unreachable'> {
    if (!this.cached?.heartbeatUrl) return 'ok';
    try {
      const controller = new AbortController();
      const t = setTimeout(() => controller.abort(), 5000);
      const res = await fetch(this.cached.heartbeatUrl, {
        method: 'POST',
        headers: { 'content-type': 'application/json' },
        body: JSON.stringify({ client: this.cached.clientName }),
        signal: controller.signal,
      });
      clearTimeout(t);
      if (!res.ok) return 'unreachable';
      const body = (await res.json()) as { revoked?: boolean };
      return body.revoked ? 'revoked' : 'ok';
    } catch {
      return 'unreachable';
    }
  }

  revokeLocally(): void {
    try {
      if (fs.existsSync(licensePath())) fs.unlinkSync(licensePath());
    } catch { /* ignore */ }
    this.cached = null;
  }
}
